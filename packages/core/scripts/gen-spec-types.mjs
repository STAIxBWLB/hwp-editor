#!/usr/bin/env node
/**
 * Generate TypeScript types from the frozen hwp-cli JSON schemas in
 * packages/core/schemas/. Output is committed under src/generated/; re-run
 * with `pnpm gen:types` when the schemas are re-pinned.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemasDir = join(here, "..", "schemas");
const outDir = join(here, "..", "src", "generated");

/** schema file -> [output file, exported type name] */
const SPECS = [
  ["document-spec-v2.schema.json", "document-spec-v2.ts", "DocumentSpecV2"],
  ["template-spec-v1.schema.json", "template-spec-v1.ts", "TemplateSpecV1"],
  ["template-data-v1.schema.json", "template-data-v1.ts", "TemplateDataV1"],
];

const HEADER =
  "/* eslint-disable */\n" +
  "/**\n" +
  " * Generated by scripts/gen-spec-types.mjs from schemas/ (pinned copy of\n" +
  " * hwp-cli v0.8.7 JSON schemas). Do not edit by hand.\n" +
  " */\n\n";

await mkdir(outDir, { recursive: true });

for (const [schemaFile, outFile, typeName] of SPECS) {
  const schema = JSON.parse(
    await readFile(join(schemasDir, schemaFile), "utf8"),
  );
  // json-schema-to-typescript derives the type name from `title`; override.
  schema.title = typeName;
  const ts = await compile(schema, typeName, {
    bannerComment: "",
    format: false,
    strictIndexSignatures: true,
    // Resolve relative $refs (e.g. document-spec-v2 -> document-spec-v1)
    // against the pinned schemas directory.
    cwd: schemasDir,
  });
  await writeFile(join(outDir, outFile), HEADER + ts, "utf8");
  console.log(`generated src/generated/${outFile}`);
}
